// Generates src/data/slugIndex.ts: tiny id->slug maps for products and blog posts.
// The router needs to know which URL slugs are products or posts without importing the
// (large) data modules, so the catalogue and article text can load only with the pages that use them.
// Runs automatically before `dev` and `build` (see package.json).
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { pathToFileURL } from 'node:url';

const root = path.resolve(import.meta.dirname, '..');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'slugidx-'));
const outfile = path.join(tmp, 'data.mjs');

await build({
  stdin: {
    contents: `export { PRODUCTS } from './src/data/products.ts'; export { BLOG_POSTS } from './src/data/blogPosts.ts';`,
    resolveDir: root,
    loader: 'ts'
  },
  bundle: true,
  format: 'esm',
  platform: 'node',
  outfile,
  logLevel: 'error'
});
const { PRODUCTS, BLOG_POSTS } = await import(pathToFileURL(outfile).href);
fs.rmSync(tmp, { recursive: true, force: true });

const rec = (items) => '{\n' + items.map((x) => `  ${JSON.stringify(x.id)}: ${JSON.stringify(x.slug)}`).join(',\n') + '\n}';
const src = `// GENERATED by scripts/gen-slug-index.mjs - do not edit by hand.
export const PRODUCT_SLUG_BY_ID: Record<string, string> = ${rec(PRODUCTS)};

export const BLOG_SLUG_BY_ID: Record<string, string> = ${rec(BLOG_POSTS)};

export interface BlogCard {
  id: string;
  slug: string;
  title: string;
  excerpt: string;
  image: string;
  category: string;
  readTime: string;
}
// Light card data (no article text) so the homepage doesn't need the full posts.
export const BLOG_CARDS: BlogCard[] = ${JSON.stringify(BLOG_POSTS.map((b) => ({ id: b.id, slug: b.slug, title: b.title, excerpt: b.excerpt, image: b.image, category: b.category, readTime: b.readTime })), null, 2)};

export const PRODUCT_SLUGS = new Set(Object.values(PRODUCT_SLUG_BY_ID));
export const BLOG_SLUGS = new Set(Object.values(BLOG_SLUG_BY_ID));
`;
const target = path.join(root, 'src/data/slugIndex.ts');
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== src) fs.writeFileSync(target, src);
console.log(`slug index: ${PRODUCTS.length} products, ${BLOG_POSTS.length} posts`);
